"""Generate android_content_res.h from frameworks/base flags.aconfig.

libandroidfw uses aconfig generated accessors such as
``android_content_res_xml_file_size_limit()``.  Soong runs the aconfig code
generator for the build; a standalone cmake build has no aconfig, so the header
is missing and AssetsProvider.cpp fails with

    fatal error: 'android_content_res.h' file not found

This generator reads the flag declarations of the very tag being built and emits
one static inline accessor per flag.  Every flag is reported as off, which means
the build takes the code path that existed before the flag was introduced - the
same path libandroidfw used before the accessor appeared.  Nothing is hard coded,
so a newer build-tools version with new flags keeps compiling.
"""

import argparse
import re
import sys


def read_flags(aconfig_path):
    """Return the flag names declared in an aconfig file, in file order."""
    text = aconfig_path.read_text()
    names = []
    for match in re.finditer(r'(?m)^\s*flag\s*\{', text):
        start = text.index('{', match.start())
        depth = 0
        end = None
        for pos in range(start, len(text)):
            char = text[pos]
            if char == '{':
                depth += 1
            elif char == '}':
                depth -= 1
                if depth == 0:
                    end = pos
                    break
        if end is None:
            raise ValueError('unterminated flag block at offset %d' % match.start())
        block = text[start:end]
        found = re.search(r'name\s*:\s*"([A-Za-z0-9_]+)"', block)
        if not found:
            raise ValueError('flag block without a name at offset %d' % match.start())
        if found.group(1) not in names:
            names.append(found.group(1))
    return names


def render(names, package, source):
    lines = [
        '// Generated by scripts/gen_content_res_flags.py - do not edit.',
        '//',
        '// Source: %s' % source,
        '// Package: %s' % package,
        '//',
        '// AOSP generates this header with aconfig during a Soong build; a standalone',
        '// cmake build has no aconfig codegen.  Every flag is reported as off, so the',
        '// build stays on the code path that existed before the flag was introduced.',
        '#pragma once',
        '',
        '#ifndef ANDROID_CONTENT_RES_FLAGS_H',
        '#define ANDROID_CONTENT_RES_FLAGS_H',
        '',
    ]
    if not names:
        lines.append('// The flags.aconfig of this tag declares no flags.')
        lines.append('')
    for name in names:
        lines.append('static inline bool android_content_res_%s() { return false; }' % name)
    lines.extend(['', '#endif  // ANDROID_CONTENT_RES_FLAGS_H', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('aconfig', help='path to core/java/android/content/res/flags.aconfig')
    parser.add_argument('output', help='header to write')
    args = parser.parse_args()

    aconfig_path = args.aconfig
    output = args.output

    try:
        aconfig = open(aconfig_path, encoding='utf-8')
    except OSError as error:
        print('error: cannot read %s: %s' % (aconfig_path, error), file=sys.stderr)
        return 1
    with aconfig:
        text = aconfig.read()

    import pathlib
    package = 'android.content.res'
    found = re.search(r'(?m)^\s*package\s*:\s*"([^"]+)"', text)
    if found:
        package = found.group(1)
    names = read_flags(pathlib.Path(aconfig_path))
    header = render(names, package, aconfig_path)

    pathlib.Path(output).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(output).write_text(header)
    print('android_content_res.h: %d flags from %s -> %s' % (len(names), aconfig_path, output))
    return 0


if __name__ == '__main__':
    sys.exit(main())
